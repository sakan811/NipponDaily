#!/usr/bin/env -S node --experimental-strip-types --no-warnings
/**
 * Builds data/reference/{n4,n3,n2}-reference.json — the same kind of
 * committed, versioned dictionary-evidence snapshot as N5's
 * data/reference/n5-reference.json (see scripts/build-n5-reference.mjs and
 * docs/content-accuracy.md), for the N4/N3/N2 word lists.
 *
 * Deliberately kept separate from build-n5-reference.mjs and NOT wired into
 * test/content/'s gating checks: those checks verify NipponDaily's
 * hand-written content (lesson prose, example sentences, meaning
 * corrections) against evidence, and none of that hand-written content
 * exists for N4-N2 yet — no WORD_CLUSTERS, no shared/meanings.ts
 * corrections, nothing has been through a verification pass. Running the
 * same "every word must cleanly resolve in JMdict" gate against ~4,500
 * words straight from the raw word list would fail on pre-existing
 * word-list quality issues nobody has reviewed, the same way N5's own list
 * needed VOCAB_FORM_CORRECTIONS/VOCAB_MEANING_OVERRIDES entries added over
 * time as they were found — not something to inherit in bulk unreviewed.
 *
 * What these files ARE for: real, checksum-verified JMdict/KANJIDIC2
 * evidence for every N4/N3/N2 word and its kanji, ready for whoever
 * authors that level's WORD_CLUSTERS next to check hand-written claims
 * against — the "verify" half of the draft-then-verify pipeline, in place
 * before there's anything to verify yet.
 *
 * Each output file's `meta.unresolvedInJmdict` lists every word that didn't
 * cleanly resolve — the same discovery step VOCAB_FORM_CORRECTIONS grew out
 * of for N5, surfaced upfront here instead of found one CI failure at a time.
 *
 * Usage: pnpm data:reference:jlpt
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseJlptCsv, slugify } from "./seed-pool-data.mjs";
import { WORD_LIST_SOURCES, wordListUrl } from "./word-list-source.mjs";
import {
  JAMDICT_SOURCE,
  ensureJamdictDb,
  openDictionary,
} from "./lib/jamdict.mjs";
import { servedVocab } from "../shared/meanings.ts";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CACHE_DIR = join(ROOT, "node_modules/.cache/n5-reference");
const LEVELS = ["N4", "N3", "N2"];

const KANJI_RE_G = /[㐀-䶿一-鿿]/gu;

async function fetchWordList(level) {
  const res = await fetch(wordListUrl(level));
  if (!res.ok) throw new Error(`GET ${wordListUrl(level)} → ${res.status}`);
  return parseJlptCsv(await res.text(), level);
}

function buildLevelReference(level, entries, dict) {
  const seen = new Set();
  const unresolvedInJmdict = [];

  // Same shape as N5's reference.vocab (id/seedKey/term/kana/meaning/
  // listTerm/listReading/listMeaning/jmdict) — servedVocab() is applied so
  // this reflects what GET /api/pool-vocab?level=<level> would actually
  // serve today, even though no corrections exist yet for these levels.
  const vocab = entries.map((e) => {
    const id = slugify(e.term, seen);
    const served = servedVocab({ ...e, romaji: "" });
    const jmdict = dict.lookupWord(served.term, served.kana);
    if (jmdict.length === 0) {
      unresolvedInJmdict.push(`${id}: ${served.term} (${served.kana})`);
    }
    return {
      id,
      seedKey: `${e.term} ${e.kana}`,
      term: served.term,
      kana: served.kana,
      meaning: served.meaning,
      listTerm: e.term,
      listReading: e.listReading,
      listMeaning: e.listMeaning,
      jlptLevel: level,
      jmdict,
    };
  });

  const kanjiChars = new Set();
  for (const v of vocab)
    for (const c of v.term.match(KANJI_RE_G) ?? []) kanjiChars.add(c);
  const kanji = {};
  for (const c of [...kanjiChars].sort()) {
    const info = dict.kanji(c);
    if (info) kanji[c] = info;
  }

  return {
    meta: {
      description: `Dictionary evidence for ${level} words — same idea as data/reference/n5-reference.json, but not (yet) gated in test/content/: see this file's own header comment in scripts/build-jlpt-reference.mjs for why. Generated by \`pnpm data:reference:jlpt\` — do not edit by hand.`,
      level,
      sources: {
        jmdict: {
          ...JAMDICT_SOURCE,
          licence: "JMdict/KANJIDIC2 © EDRDG, CC BY-SA 4.0",
        },
        wordList: { ...WORD_LIST_SOURCES[level], licence: "MIT" },
      },
      counts: {
        vocab: vocab.length,
        kanji: Object.keys(kanji).length,
        unresolvedInJmdict: unresolvedInJmdict.length,
      },
      unresolvedInJmdict,
    },
    vocab,
    kanji,
  };
}

async function main() {
  const dbPath = await ensureJamdictDb(CACHE_DIR);
  const dict = openDictionary(dbPath);

  for (const level of LEVELS) {
    const entries = await fetchWordList(level);
    console.log(`Loaded ${entries.length} ${level} word-list entries`);
    const reference = buildLevelReference(level, entries, dict);

    const outFile = join(
      ROOT,
      `data/reference/${level.toLowerCase()}-reference.json`,
    );
    mkdirSync(dirname(outFile), { recursive: true });
    writeFileSync(outFile, `${JSON.stringify(reference, null, 1)}\n`);
    console.log(
      `Wrote ${outFile}: ${reference.meta.counts.vocab} vocab, ${reference.meta.counts.kanji} kanji, ` +
        `${reference.meta.counts.unresolvedInJmdict} unresolved in JMdict`,
    );
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}

export { fetchWordList, buildLevelReference };
