/**
 * Builds data/reference/etymology/ (`pnpm data:etymology`): one YYYY-MM.json
 * shard per word-plan month plus meta.json (see scripts/lib/etymology-snapshot.mjs).
 *
 * Every daily word quotes its origin from English Wiktionary's Japanese
 * Etymology section (the entries under data/words/ are generated from this
 * snapshot — see scripts/lib/word-entry.mjs). Nothing in JMdict/KANJIDIC2
 * backs those claims, so this snapshot is the committed evidence, and
 * test/content/words.test.ts checks every quote against it.
 *
 * Offline and deterministic: the sections are read from one pinned Kaikki.org
 * wiktextract dump (scripts/lib/wiktionary-dump.mjs), whose checksum is
 * verified first, so the same dump gives the same snapshot. Bumping the dump is
 * a deliberate change to that pin, followed by a re-run and a review of the diff.
 *
 * Each Etymology section records the reading(s) the page's own headword
 * templates declare for it (`readings`), so an entry can quote only the section
 * for its own reading — a page like 大人 has one section for each of おとな,
 * うし, たいじん and だいにん.
 *
 * Terms are every entry's `term` in data/words/*.json, every term in
 * data/word-plan/*.json, every term already in the snapshot, plus an optional
 * `--terms a,b,c` for a batch with no plan yet. `--prune` drops pins nothing
 * uses. `--skip-missing` logs and skips a term the dump has no Etymology for
 * (instead of aborting the run), for bulk candidate batches.
 * `--dump <path>` (or WIKTIONARY_DUMP) names the dump file; by default it is
 * the pinned file name in the repo root.
 *
 * Wiktionary text is CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/);
 * the snapshot keeps each page's link so the attribution stays traceable.
 */
import { readFileSync, readdirSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  WIKTIONARY_DUMP,
  readSections,
  verifyDump,
} from "./lib/wiktionary-dump.mjs";
import {
  loadEtymologySnapshot,
  planMonths,
  writeEtymologySnapshot,
} from "./lib/etymology-snapshot.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const args = process.argv.slice(2);
const flagValue = (name) => {
  const i = args.indexOf(name);
  return i === -1 ? undefined : args[i + 1];
};
const listFlag = (name) => (flagValue(name) ?? "").split(",").filter(Boolean);

function entryTerms() {
  const dir = join(ROOT, "data/words");
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .flatMap((f) =>
      JSON.parse(readFileSync(join(dir, f), "utf8")).map((e) => e.term),
    );
}

// What nothing but a removed word leaves behind: `--prune` keeps only terms an
// entry, a plan or `--terms` still names.
const used = new Set([
  ...entryTerms(),
  ...Object.keys(planMonths(ROOT)),
  ...listFlag("--terms"),
]);
const existing = loadEtymologySnapshot(ROOT);
const terms = [
  ...new Set([
    ...(args.includes("--prune") ? [] : Object.keys(existing.entries ?? {})),
    ...used,
  ]),
].sort();
if (terms.length === 0)
  throw new Error(
    "No terms: add data/words/*.json entries, a word plan or pass --terms a,b,c",
  );

const dumpPath = resolve(
  flagValue("--dump") ??
    process.env.WIKTIONARY_DUMP ??
    join(ROOT, WIKTIONARY_DUMP.file),
);
if (!existsSync(dumpPath))
  throw new Error(
    `No Wiktionary dump at ${dumpPath}. Download ${WIKTIONARY_DUMP.url} (or pass --dump <path>).`,
  );
console.log(`Verifying ${dumpPath}…`);
await verifyDump(dumpPath);
console.log(`Reading ${terms.length} terms…`);
const sections = await readSections(dumpPath, terms);

const entries = {};
for (const term of terms) {
  const etymologies = sections.get(term);
  if (!etymologies) {
    if (!args.includes("--skip-missing"))
      throw new Error(`${term}: no Japanese Etymology section in the dump`);
    console.log(`${term}: skipped (no Japanese Etymology section)`);
    continue;
  }
  entries[term] = {
    url: `https://en.wiktionary.org/wiki/${encodeURIComponent(term)}`,
    etymologies,
  };
}

const meta = {
  source: `English Wiktionary (https://en.wiktionary.org), Japanese Etymology sections, read from the ${WIKTIONARY_DUMP.dump} dump as extracted by wiktextract on ${WIKTIONARY_DUMP.extracted} (Kaikki.org)`,
  license: "CC BY-SA 4.0 — https://creativecommons.org/licenses/by-sa/4.0/",
  dump: WIKTIONARY_DUMP.dump,
  extracted: WIKTIONARY_DUMP.extracted,
  file: WIKTIONARY_DUMP.file,
  sha256: WIKTIONARY_DUMP.sha256,
  note: "Generated by `pnpm data:etymology` — never edit by hand. Quotes in data/words/*.json are checked against `etymologies[].text`.",
};
const shards = writeEtymologySnapshot(ROOT, meta, entries);
console.log(
  `Wrote ${Object.keys(entries).length} pins into ${shards} file(s) under data/reference/etymology/`,
);
