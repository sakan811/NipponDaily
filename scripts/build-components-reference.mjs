/**
 * Builds data/reference/components.json (`pnpm data:components`): the parts
 * every kanji of the daily words is built from, taken from the KRADFILE of the
 * Electronic Dictionary Research and Development Group (EDRDG), pinned by
 * size and checksum below. It lists, for a kanji, the radicals and other
 * elements it is made of (亜 is ｜, 一 and 口), in the group's own notation,
 * which is not always a kanji (｜, ノ, 丶).
 *
 * Nothing is guessed: a kanji the file has no line for gets no entry, and the
 * parts are copied as the file gives them. The archive is downloaded, checked
 * against its size and checksum, and cached; the build is otherwise offline
 * and deterministic. `kradfile` covers the kanji of JIS X 0208 and `kradfile2`
 * those of JIS X 0212; a kanji on both keeps the first.
 *
 *   node scripts/build-components-reference.mjs [--file <path>] [--check]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { LICENCES, SOURCES } from "../shared/sources.ts";
import { ROOT, args, flagValue } from "./lib/cli.mjs";
import { pinnedFile } from "./lib/pinned-file.mjs";
import { readZipFile } from "./lib/zip.mjs";

const OUT_FILE = "data/reference/components.json";
const CACHE_DIR = join(ROOT, "node_modules/.cache/components");

export const COMPONENTS_SOURCE = {
  name: "KRADFILE",
  file: "kradzip.zip",
  url: "https://www.edrdg.org/pub/Nihongo/kradzip.zip",
  /** The files read from the archive, in the order they are tried. */
  members: ["kradfile", "kradfile2"],
  bytes: 285669,
  sha256: "e2df44c07ed557fe9867709a051f1f134cd33c750598112d85ba56eb86fc3c8c",
  licence: LICENCES.ccBySa4.name,
};

/** The meta the snapshot carries. */
export function snapshotMeta() {
  return {
    source: `${COMPONENTS_SOURCE.name} (${SOURCES.edrdg.url}), copyright ${SOURCES.edrdg.holder}`,
    licence: `${LICENCES.ccBySa4.name} — ${LICENCES.ccBySa4.url}`,
    file: {
      name: COMPONENTS_SOURCE.file,
      url: COMPONENTS_SOURCE.url,
      members: COMPONENTS_SOURCE.members,
      bytes: COMPONENTS_SOURCE.bytes,
      sha256: COMPONENTS_SOURCE.sha256,
    },
    note: "Generated by `pnpm data:components`: never edit by hand. Each kanji maps to the parts KRADFILE lists for it, in its order and notation (a part need not be a kanji).",
  };
}

/** The archive's `kradfile` and `kradfile2` as text (both are EUC-JP). */
async function memberTexts(path) {
  const data = await pinnedFile({
    path,
    cacheFile: join(CACHE_DIR, COMPONENTS_SOURCE.file),
    url: COMPONENTS_SOURCE.url,
    label: COMPONENTS_SOURCE.name,
    what: COMPONENTS_SOURCE.file,
    pin: COMPONENTS_SOURCE,
  });
  const decoder = new TextDecoder("euc-jp", { fatal: true });
  return COMPONENTS_SOURCE.members.map((name) =>
    decoder.decode(readZipFile(data, name)),
  );
}

/** `character → parts` from the lines (`亜 : ｜ 一 口`) of KRADFILE texts;
 *  comment lines start with `#`. */
export function parseComponents(texts) {
  const out = new Map();
  for (const text of texts)
    for (const line of text.split("\n")) {
      if (!line || line.startsWith("#")) continue;
      const [char, parts] = line.split(" : ");
      const list = (parts ?? "").trim().split(/\s+/).filter(Boolean);
      if (char && list.length && !out.has(char)) out.set(char, list);
    }
  return out;
}

/** The snapshot's parts for the given kanji (`char → KANJIDIC2 record`). */
export function buildComponents(kanji, listed) {
  const components = {};
  for (const char of Object.keys(kanji))
    if (listed.has(char)) components[char] = listed.get(char);
  return components;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const kanji = JSON.parse(
    readFileSync(join(ROOT, "data/reference/kanji.json"), "utf8"),
  ).kanji;
  const components = buildComponents(
    kanji,
    parseComponents(await memberTexts(flagValue("--file"))),
  );
  const next = `${JSON.stringify({ meta: snapshotMeta(), components })}\n`;
  if (args.includes("--check")) {
    const prev = existsSync(join(ROOT, OUT_FILE))
      ? readFileSync(join(ROOT, OUT_FILE), "utf8")
      : "";
    if (prev !== next) {
      console.error(`${OUT_FILE} is out of date: run pnpm data:components`);
      process.exit(1);
    }
    console.log(`Checked ${OUT_FILE}`);
  } else {
    writeFileSync(join(ROOT, OUT_FILE), next);
    const left = Object.keys(kanji).filter((c) => !(c in components));
    console.log(
      `Wrote parts for ${Object.keys(components).length} of ${Object.keys(kanji).length} kanji into ${OUT_FILE}${left.length ? `; none for ${left.join("")}` : ""}`,
    );
  }
}
