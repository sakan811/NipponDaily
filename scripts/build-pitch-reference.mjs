/**
 * Builds data/reference/pitch.json (`pnpm data:pitch`): the pitch accent of
 * every daily word that the pinned accent list gives for that exact spelling
 * and reading.
 *
 * The list is Kanjium's accents.txt (https://github.com/mifunetoshiro/kanjium,
 * CC BY-SA 4.0), one line per `spelling<TAB>reading<TAB>accents`, the accent
 * being the number of the mora after which the pitch falls (0: it does not).
 * A kana-only word has an empty reading column. The file is downloaded from
 * the pinned commit, checked against its size and checksum, and cached; the
 * build is otherwise offline and deterministic.
 *
 * One list is one source, so each accent is then checked against a second,
 * UniDic's accent type for the same spelling and reading
 * (scripts/lib/unidic-accent.mjs). An accent is kept only where both give it;
 * the rest are written to `heldBack`, with what each source said, so the words
 * they disagree on, or UniDic is silent on, can be named.
 *
 * Nothing is guessed: a word whose spelling and reading are not both on a line
 * gets no pitch, and so does a word whose number is more than it has morae.
 * The word plans and the committed level snapshots say which words there are,
 * so a snapshot can be made before `pnpm data:words`.
 *
 *   node scripts/build-pitch-reference.mjs [--file <path>] [--unidic <sys.dic>] [--check]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { toHiragana } from "wanakana";
import { LICENCES, SOURCES } from "../shared/sources.ts";
import { ROOT, args, flagValue } from "./lib/cli.mjs";
import { pinnedFile } from "./lib/pinned-file.mjs";
import { poolWords } from "./lib/pool-words.mjs";
import { moraeOf } from "../app/utils/pitch.ts";
import {
  MecabDictionary,
  UNIDIC_ACCENT_SOURCE,
  agreedAccents,
  loadUnidicDictionary,
  unidicAccents,
} from "./lib/unidic-accent.mjs";

const OUT_FILE = "data/reference/pitch.json";
const CACHE_DIR = join(ROOT, "node_modules/.cache/pitch");

export const PITCH_SOURCE = {
  name: "Kanjium accents.txt",
  repo: "mifunetoshiro/kanjium",
  commit: "9ebca4589565c696e7c39e089e2e928ad65f678c",
  committed: "2026-10-03",
  path: "data/source_files/raw/accents.txt",
  bytes: 3226405,
  sha256: "8bd0dd127dab32ceec94cb03ab1ba6b68858ea73421dfa1731af2f373deb4f20",
  licence: LICENCES.ccBySa4.name,
};
const URL = `https://raw.githubusercontent.com/${PITCH_SOURCE.repo}/${PITCH_SOURCE.commit}/${PITCH_SOURCE.path}`;

/** The meta the snapshot carries. */
export function snapshotMeta() {
  return {
    source: `${PITCH_SOURCE.name} (${SOURCES.kanjium.url}), commit ${PITCH_SOURCE.commit} of ${PITCH_SOURCE.committed}`,
    licence: `${LICENCES.ccBySa4.name} — ${LICENCES.ccBySa4.url}`,
    file: {
      path: PITCH_SOURCE.path,
      bytes: PITCH_SOURCE.bytes,
      sha256: PITCH_SOURCE.sha256,
    },
    check: {
      source: `${UNIDIC_ACCENT_SOURCE.name} (${UNIDIC_ACCENT_SOURCE.url})`,
      licence: UNIDIC_ACCENT_SOURCE.licence,
      file: {
        path: UNIDIC_ACCENT_SOURCE.entry,
        bytes: UNIDIC_ACCENT_SOURCE.dicBytes,
        archiveBytes: UNIDIC_ACCENT_SOURCE.bytes,
        archiveSha256: UNIDIC_ACCENT_SOURCE.sha256,
      },
    },
    note: "Generated by `pnpm data:pitch`: never edit by hand. Each key of `entries` is a daily word's spelling; `kana` is its reading and `accents` the mora after which the pitch falls (0: it never falls), kept only where Kanjium and UniDic both give it. `heldBack` names each word with an accent that was not kept, with what `kanjium` and `unidic` gave (`unidic` empty: it has no accent for that spelling and reading).",
  };
}

/** The list's text, downloaded to the cache if need be and verified. */
async function accentText(path) {
  const data = await pinnedFile({
    path,
    cacheFile: join(CACHE_DIR, "accents.txt"),
    url: URL,
    label: PITCH_SOURCE.name,
    what: "accents.txt",
    pin: PITCH_SOURCE,
  });
  return data.toString("utf8");
}

/** The list as `spelling → reading → accents`, in the file's order. A
 *  kana-only word's empty reading column is its own spelling. */
export function parseAccents(text) {
  const table = new Map();
  for (const line of text.split("\n")) {
    const [term, reading, accents] = line.split("\t");
    if (!term || accents === undefined) continue;
    const kana = toHiragana(reading || term);
    const list = table.get(term) ?? new Map();
    const known = list.get(kana) ?? [];
    for (const a of accents.trim().split(",")) {
      const n = Number(a);
      if (/^\d+$/.test(a.trim()) && !known.includes(n)) known.push(n);
    }
    list.set(kana, known);
    table.set(term, list);
  }
  return table;
}

/** The snapshot entries for every word: only an exact spelling and reading,
 *  and only numbers the word has the morae for. */
export function buildPitch(words, table) {
  const entries = {};
  for (const { term, kana } of words) {
    const accents = table.get(term)?.get(toHiragana(kana));
    if (!accents?.length) continue;
    const count = moraeOf(kana).length;
    if (accents.some((a) => a > count)) continue;
    entries[term] = { kana, accents };
  }
  return entries;
}

/** Keeps of each word's accents those UniDic gives too. `entries` are the
 *  words with at least one, `heldBack` every word that lost any. */
export function checkPitch(listed, dict) {
  const entries = {};
  const heldBack = {};
  for (const [term, { kana, accents }] of Object.entries(listed)) {
    const second = unidicAccents(dict, term, kana);
    const agreed = agreedAccents(accents, second);
    if (agreed.length) entries[term] = { kana, accents: agreed };
    if (agreed.length < accents.length)
      heldBack[term] = { kana, kanjium: accents, unidic: second };
  }
  return { entries, heldBack };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const table = parseAccents(await accentText(flagValue("--file")));
  const dict = new MecabDictionary(
    await loadUnidicDictionary(CACHE_DIR, flagValue("--unidic")),
  );
  const { entries, heldBack } = checkPitch(
    buildPitch(poolWords(ROOT), table),
    dict,
  );
  const next = `${JSON.stringify({ meta: snapshotMeta(), entries, heldBack }, null, 1)}\n`;
  if (args.includes("--check")) {
    const prev = existsSync(join(ROOT, OUT_FILE))
      ? readFileSync(join(ROOT, OUT_FILE), "utf8")
      : "";
    if (prev !== next) {
      console.error(`${OUT_FILE} is out of date: run pnpm data:pitch`);
      process.exit(1);
    }
    console.log(`Checked ${OUT_FILE}`);
  } else {
    writeFileSync(join(ROOT, OUT_FILE), next);
    console.log(
      `Wrote pitch accents for ${Object.keys(entries).length} words into ${OUT_FILE}, ${Object.keys(heldBack).length} words with an accent held back`,
    );
  }
}
