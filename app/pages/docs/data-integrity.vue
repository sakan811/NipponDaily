    <h2>How an entry is built</h2>
    <DocDiagram
      label="Sources become committed snapshots, and the generator builds every entry from the snapshots alone"
      :nodes="build.nodes"
      :edges="build.edges"
    />
    <p>
      <code>scripts/lib/word-entry.mjs</code> builds an entry from sources only
      (<code>scripts/generate-word-entries.mjs</code> runs it, and fetches
      nothing). Each step refuses rather than guess:
    </p>
    <ul>
      <li>
        <code>pickSections</code> picks the Wiktionary section whose declared
        reading covers the word's.
      </li>
      <li>
        <code>evidenceLines</code> yields one verbatim quote per line, minus
        Wikipedia furniture.
      </li>
      <li>
        <code>parseMorphemes</code> reads
        <code>A (a, “gloss”) + B (b, “gloss”)</code> chains and keeps them only
        if the parts spell the word and join to its reading (rendaku allowed).
        It also accepts a stem glossed through its base verb (缶詰), a dropped
        okurigana (出る → 出口) and bare kana parts (お), and picks nothing when
        two different splits fit.
      </li>
      <li>
        <code>parseLiteral</code> pairs a “warm + spring” style gloss with
        KANJIDIC2's unambiguous per-kanji readings; <code>parseLoan</code>
        handles loanwords.
      </li>
      <li>
        <code>parseKanji</code> is the last resort for a word written with kanji
        (and the okurigana after them) that the text doesn't split: one part per
        kanji, with the okurigana that follow it (手続き is 手 + 続き, 言い出す
        is 言い + 出す), KANJIDIC2's reading and a meaning the text or the
        JMdict meaning already uses, marked
        <code>glossSource: "kanjidic2"</code>. It is refused for ateji,
        jukujikun, an ambiguous split, kana KANJIDIC2 does not list as okurigana
        (何でも), and a single kanji with its okurigana, which would only repeat
        the word.
      </li>
      <li>
        <code>processesOf</code> finds keyword tags in the quoted text and adds
        what JMdict, a source independent of Wiktionary, records for the matched
        sense: a coinage made in Japan, an ateji or jukujikun spelling, a loan
        source (<code>jmdictFactsOf</code>). <code>stratumOf</code> analyses
        KANJIDIC2's on and kun readings, and takes a JMdict loan source as the
        loanword layer unless the cited text names Chinese.
      </li>
    </ul>

