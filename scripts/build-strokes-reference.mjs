/**
 * Builds data/reference/strokes.json (`pnpm data:strokes`): the strokes of
 * every kanji the daily words are written with, in the order they are drawn,
 * taken from one pinned KanjiVG release (https://kanjivg.tagaini.net,
 * Ulrich Apel, CC BY-SA 3.0).
 *
 * KanjiVG draws each kanji on a 109 by 109 square as one SVG path per stroke.
 * The paths are copied verbatim. A kanji is kept only where KanjiVG draws the
 * same number of strokes as KANJIDIC2 counts for it (two independent sources),
 * so a variant drawn differently shows no strokes instead of a doubtful
 * order. The release is downloaded, checked against its size and checksum, and
 * cached; the build is otherwise offline and deterministic.
 *
 *   node scripts/build-strokes-reference.mjs [--file <path>] [--check]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { gunzipSync } from "node:zlib";
import { LICENCES, SOURCES } from "../shared/sources.ts";
import { ROOT, args, flagValue } from "./lib/cli.mjs";
import { pinnedFile } from "./lib/pinned-file.mjs";

const OUT_FILE = "data/reference/strokes.json";
const CACHE_DIR = join(ROOT, "node_modules/.cache/strokes");

export const STROKES_SOURCE = {
  name: "KanjiVG",
  release: "r20260714",
  file: "kanjivg-20260714.xml.gz",
  url: "https://github.com/KanjiVG/kanjivg/releases/download/r20260714/kanjivg-20260714.xml.gz",
  bytes: 3608635,
  sha256: "d4a8e5e11533fe6a5d81a158b2c153964322641d2982c90a919461f3c06dca6b",
  licence: LICENCES.ccBySa3.name,
};

/** The meta the snapshot carries. */
export function snapshotMeta() {
  return {
    source: `${STROKES_SOURCE.name} ${STROKES_SOURCE.release} (${SOURCES.kanjivg.url}), copyright ${SOURCES.kanjivg.holder}`,
    licence: `${LICENCES.ccBySa3.name} — ${LICENCES.ccBySa3.url}`,
    file: {
      name: STROKES_SOURCE.file,
      url: STROKES_SOURCE.url,
      bytes: STROKES_SOURCE.bytes,
      sha256: STROKES_SOURCE.sha256,
    },
    viewBox: "0 0 109 109",
    note: "Generated by `pnpm data:strokes`: never edit by hand. Each kanji maps to its strokes in the order they are drawn, as SVG path data on a 109 by 109 square; a kanji is kept only where KanjiVG and KANJIDIC2 count the same number of strokes.",
  };
}

/** The release's text, downloaded to the cache if need be and verified. */
async function releaseText(path) {
  const data = await pinnedFile({
    path,
    cacheFile: join(CACHE_DIR, STROKES_SOURCE.file),
    url: STROKES_SOURCE.url,
    label: `${STROKES_SOURCE.name} ${STROKES_SOURCE.release}`,
    what: STROKES_SOURCE.file,
    pin: STROKES_SOURCE,
  });
  return gunzipSync(data).toString("utf8");
}

/** Every plain kanji (not its `-Kaisho` or `-Jinmei` variants) of the release
 *  as `character → stroke paths in drawing order`. */
export function parseStrokes(xml) {
  const out = new Map();
  for (const [, hex, body] of xml.matchAll(
    /<kanji id="kvg:kanji_([0-9a-f]{5})">([\s\S]*?)<\/kanji>/g,
  )) {
    const strokes = [];
    for (const m of body.matchAll(
      /<path id="kvg:[0-9a-f]{5}-s(\d+)"[^>]*? d="([^"]*)"/g,
    ))
      strokes[Number(m[1]) - 1] = m[2];
    if (strokes.length && strokes.every((d) => typeof d === "string"))
      out.set(String.fromCodePoint(parseInt(hex, 16)), strokes);
  }
  return out;
}

/** The snapshot's strokes for the given kanji (`char → KANJIDIC2 record`),
 *  keeping those both sources count alike. */
export function buildStrokes(kanji, drawn) {
  const strokes = {};
  for (const [char, record] of Object.entries(kanji)) {
    const paths = drawn.get(char);
    if (paths && paths.length === record.strokeCount) strokes[char] = paths;
  }
  return strokes;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const kanji = JSON.parse(
    readFileSync(join(ROOT, "data/reference/kanji.json"), "utf8"),
  ).kanji;
  const strokes = buildStrokes(
    kanji,
    parseStrokes(await releaseText(flagValue("--file"))),
  );
  const next = `${JSON.stringify({ meta: snapshotMeta(), strokes })}\n`;
  if (args.includes("--check")) {
    const prev = existsSync(join(ROOT, OUT_FILE))
      ? readFileSync(join(ROOT, OUT_FILE), "utf8")
      : "";
    if (prev !== next) {
      console.error(`${OUT_FILE} is out of date: run pnpm data:strokes`);
      process.exit(1);
    }
    console.log(`Checked ${OUT_FILE}`);
  } else {
    writeFileSync(join(ROOT, OUT_FILE), next);
    const left = Object.keys(kanji).filter((c) => !(c in strokes));
    console.log(
      `Wrote strokes for ${Object.keys(strokes).length} of ${Object.keys(kanji).length} kanji into ${OUT_FILE}${left.length ? `; none for ${left.join("")}` : ""}`,
    );
  }
}
