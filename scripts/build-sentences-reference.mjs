/**
 * Builds data/reference/sentences/ (`pnpm data:sentences`): the example
 * sentences of every daily word, picked from one pinned Tatoeba export
 * (scripts/lib/tatoeba-export.mjs) by the rules in
 * scripts/lib/example-sentences.mjs.
 *
 * Offline and deterministic: the export's checksums are verified first, and the
 * same export gives the same snapshot. The pool word (reading, spelling and
 * whether JMdict reads the spelling several ways) comes from the word plans and
 * the committed level snapshots. Words with no qualifying sentence simply get
 * none. Of a word's qualifying sentences, those whose kanji are all read come
 * first. A sentence's furigana (scripts/lib/furigana.mjs) is Tatoeba's own
 * transcription, kept only where KANJIDIC2 or JMdict allows each reading and a
 * contributor, kuromoji, UniDic or Tatoeba's index stands behind it, so this step does
 * read the pinned JMdict and KANJIDIC2 (node_modules/.cache/, fetched and
 * checksum-verified on first use).
 *
 *   node scripts/build-sentences-reference.mjs [--dir <path>] [--check]
 *
 * `--dir` (or TATOEBA_DIR) names the directory with the extracted export; by
 * default `tatoeba/` in the repo root. `--check` fails if the committed
 * snapshot would change. Tatoeba's sentences are CC BY 2.0 FR
 * (https://creativecommons.org/licenses/by/2.0/fr/); each keeps its Tatoeba id
 * so the attribution stays traceable.
 */
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import kuromoji from "kuromoji";
import { toHiragana } from "wanakana";
import {
  TATOEBA_EXPORT,
  readExport,
  verifyExport,
} from "./lib/tatoeba-export.mjs";
import { pickExamples } from "./lib/example-sentences.mjs";
import { furiganaFor } from "./lib/furigana.mjs";
import { UNIDIC_PACKAGE, openUnidic } from "./lib/unidic.mjs";
import {
  JAMDICT_SOURCE,
  ensureJamdictDb,
  openDictionary,
} from "./lib/jamdict.mjs";
import {
  loadSentenceSnapshot,
  writeSentenceSnapshot,
} from "./lib/sentence-snapshot.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
/** Shared with the reference builders, so jamdict-data is fetched once. */
const JAMDICT_CACHE = join(ROOT, "node_modules/.cache/n5-reference");
const KUROMOJI_VERSION = createRequire(import.meta.url)(
  "kuromoji/package.json",
).version;
const args = process.argv.slice(2);
const flagValue = (name) => {
  const i = args.indexOf(name);
  return i === -1 ? undefined : args[i + 1];
};

/** The meta every snapshot carries. */
export function snapshotMeta() {
  return {
    source: `Tatoeba (https://tatoeba.org), sentences with an English translation, read from the export of ${TATOEBA_EXPORT.date}`,
    license: "CC BY 2.0 FR — https://creativecommons.org/licenses/by/2.0/fr/",
    export: TATOEBA_EXPORT.date,
    files: Object.fromEntries(
      Object.entries(TATOEBA_EXPORT.files).map(([name, f]) => [name, f.sha256]),
    ),
    furigana: `Readings from Tatoeba's own furigana of each sentence (written by a contributor, or by Tatoeba's software and then confirmed by kuromoji ${KUROMOJI_VERSION} (IPADIC) or by Lindera with UniDic (${UNIDIC_PACKAGE.name} ${UNIDIC_PACKAGE.version})), each checked against KANJIDIC2 or JMdict (${JAMDICT_SOURCE.package} ${JAMDICT_SOURCE.version}); where an analyser's own reading is confirmed by Tatoeba's index or by JMdict giving the spelling one reading, it must agree`,
    note: "Generated by `pnpm data:sentences`: never edit by hand. Each sentence's `id` is its Tatoeba number (tatoeba.org/sentences/show/<id>), `enId` its translation's; `furigana` is its parts, `[text]` or `[kanji, reading]`, which join to `ja`.",
  };
}

/** The pool word of every day in the word plans, from the committed level
 *  snapshots: the plans, not the entries, so a new month can be built before
 *  `pnpm data:words` has made its entries. */
function poolWords(root) {
  const vocab = [];
  for (const level of ["n5", "n4", "n3", "n2", "n1"])
    vocab.push(
      ...JSON.parse(
        readFileSync(
          join(root, `data/reference/${level}-reference.json`),
          "utf8",
        ),
      ).vocab,
    );
  const words = [];
  const dir = join(root, "data/word-plan");
  for (const f of readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort())
    for (const plan of JSON.parse(readFileSync(join(dir, f), "utf8"))) {
      const found = vocab.filter(
        (v) => v.term === plan.term && (!plan.kana || v.kana === plan.kana),
      );
      if (found.length !== 1)
        throw new Error(
          `${plan.term}: ${found.length} pool words with that spelling${plan.kana ? ` and reading ${plan.kana}` : "; name the reading as `kana` in the plan"}`,
        );
      words.push({
        term: plan.term,
        kana: found[0].kana,
        spellingReadings: found[0].spellingReadings,
      });
    }
  return words;
}

/** The snapshot entries for every word, from an already-read export. With a
 *  `reader` (see furiganaReader) a word's sentences with every kanji read come
 *  first, and each picked sentence gets its `furigana`. */
export function buildSentences(words, corpus, reader) {
  const entries = {};
  for (const word of words) {
    const examples = pickExamples(word, corpus, undefined, reader?.unread);
    if (!examples.length) continue;
    if (reader)
      for (const ex of examples) {
        const furigana = reader.read(ex);
        if (furigana) ex.furigana = furigana;
      }
    entries[word.term] = examples;
  }
  return entries;
}

/** What reading a sentence needs: kuromoji and UniDic, and JMdict's readings of a spelling. */
export async function openFuriganaTools() {
  const tokenizer = await new Promise((res, rej) =>
    kuromoji
      .builder({ dicPath: join(ROOT, "node_modules/kuromoji/dict") })
      .build((err, t) => (err ? rej(err) : res(t))),
  );
  const dict = openDictionary(await ensureJamdictDb(JAMDICT_CACHE));
  const memo = new Map();
  const jmdictReadings = (spelling) => {
    if (!memo.has(spelling)) memo.set(spelling, dict.readingsOf(spelling));
    return memo.get(spelling);
  };
  /** The reading of the JMdict entry the index points a word at (`前(#1392580)`),
   *  when the entry has just one. */
  const entryReading = (idseq) => {
    const all = [...new Set(dict.readingsOfEntry(idseq).map(toHiragana))];
    return all.length === 1 ? all[0] : undefined;
  };
  const kanjiMemo = new Map();
  /** Every on and kun reading KANJIDIC2 gives a kanji. */
  const kanjiReadings = (kanji) => {
    if (!kanjiMemo.has(kanji)) {
      const info = dict.kanji(kanji);
      kanjiMemo.set(kanji, info ? [...info.on, ...info.kun] : []);
    }
    return kanjiMemo.get(kanji);
  };
  return {
    tokenizer,
    unidic: openUnidic(),
    jmdictReadings,
    kanjiReadings,
    entryReading,
  };
}

/** Reads the furigana of example sentences: `read(ex)` gives a sentence's parts
 *  (scripts/lib/furigana.mjs) or undefined, and `unread(ex)` counts the kanji
 *  of the sentence left without a reading. The index's own readings of each
 *  sentence come from the export. */
export function furiganaReader(
  corpus,
  { tokenizer, unidic, jmdictReadings, kanjiReadings, entryReading },
) {
  // sentence id → [headword, reading or #entry] as the index gives them
  const indexed = new Map();
  for (const [headword, hits] of corpus.index)
    for (const hit of hits) {
      if (!hit.reading) continue;
      const list = indexed.get(hit.id);
      if (list) list.push([headword, hit.reading]);
      else indexed.set(hit.id, [[headword, hit.reading]]);
    }
  /** The index names a word's reading, or else its JMdict entry (#1392580). */
  const indexReadingsOf = (id) => {
    const out = new Map();
    for (const [headword, said] of indexed.get(id) ?? []) {
      const reading = said.startsWith("#")
        ? entryReading(Number(said.slice(1)))
        : toHiragana(said);
      if (reading) out.set(headword, reading);
    }
    return out;
  };
  const memo = new Map();
  const read = (ex) => {
    const id = String(ex.id);
    // The same sentence can serve two words, and the form each marks decides
    // where a reading may be cut.
    const key = `${id}\t${ex.form}`;
    if (!memo.has(key))
      memo.set(
        key,
        furiganaFor(ex.ja, ex.form, tokenizer.tokenize(ex.ja), {
          indexReadings: indexReadingsOf(id),
          jmdictReadings,
          kanjiReadings,
          transcription: corpus.transcriptions.get(id),
          unidicTokens: unidic?.tokenize(ex.ja),
        }),
      );
    return memo.get(key);
  };
  const KANJI = /[\p{sc=Han}々]/gu;
  const unread = (ex) => {
    const total = ex.ja.match(KANJI)?.length ?? 0;
    const read_ = (read(ex) ?? [])
      .filter((part) => part.length === 2)
      .reduce((n, [kanji]) => n + [...kanji].length, 0);
    return total - read_;
  };
  return { read, unread };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dir = resolve(
    flagValue("--dir") ??
      process.env.TATOEBA_DIR ??
      join(ROOT, TATOEBA_EXPORT.dir),
  );
  if (!existsSync(dir))
    throw new Error(
      `No Tatoeba export at ${dir}. Download the files named in scripts/lib/tatoeba-export.mjs, extract them there (or pass --dir <path>).`,
    );
  console.log(`Verifying ${dir}…`);
  await verifyExport(dir);
  console.log("Reading the export…");
  const corpus = readExport(dir);
  const entries = buildSentences(
    poolWords(ROOT),
    corpus,
    furiganaReader(corpus, await openFuriganaTools()),
  );

  if (args.includes("--check")) {
    const now = loadSentenceSnapshot(ROOT);
    // Compared by term, whatever order the shards were read in.
    const canon = (o) => JSON.stringify(Object.entries(o).sort());
    const same =
      canon(now.entries) === canon(entries) &&
      JSON.stringify(now.meta) === JSON.stringify(snapshotMeta());
    if (!same) {
      console.error(
        "data/reference/sentences/ is out of date: run pnpm data:sentences",
      );
      process.exit(1);
    }
    console.log("Checked data/reference/sentences/");
  } else {
    const shards = writeSentenceSnapshot(ROOT, snapshotMeta(), entries);
    console.log(
      `Wrote sentences for ${Object.keys(entries).length} words into ${shards} file(s) under data/reference/sentences/`,
    );
  }
}
