/**
 * Builds data/reference/kanji.json (`pnpm data:kanji`): the KANJIDIC2 record
 * of every kanji the daily words are written with, for the kanji pages.
 *
 * Offline and deterministic: it reads the committed level snapshots
 * (data/reference/n{5,4,3,2,1}-reference.json, which already hold KANJIDIC2's
 * readings, meanings, grade and frequency) and the committed entries
 * (data/words/), fetches nothing, and keeps a kanji only if a term uses it.
 * test/content/kanji.test.ts checks the file against both.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { JAMDICT_SOURCE } from "./lib/jamdict.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_FILE = "data/reference/kanji.json";
// The same range the reference builders read kanji by (no 々 or 〆).
const HAN = /[㐀-䶿一-鿿]/gu;

const readJson = (root, path) =>
  JSON.parse(readFileSync(join(root, path), "utf8"));

/** The kanji record for every character the entries' terms are written with. */
export function buildKanjiReference(root = ROOT) {
  const used = new Set();
  const wordsDir = join(root, "data/words");
  for (const file of readdirSync(wordsDir).filter((f) => f.endsWith(".json")))
    for (const { term } of readJson(root, `data/words/${file}`))
      for (const c of term.match(HAN) ?? []) used.add(c);

  const known = {};
  for (const level of ["n5", "n4", "n3", "n2", "n1"])
    Object.assign(
      known,
      readJson(root, `data/reference/${level}-reference.json`).kanji,
    );

  const missing = [...used].filter((c) => !known[c]);
  if (missing.length)
    throw new Error(
      `KANJIDIC2 has no record of ${missing.join("")}; run pnpm data:reference and pnpm data:reference:jlpt`,
    );

  const kanji = {};
  for (const c of [...used].sort((a, b) => a.codePointAt(0) - b.codePointAt(0)))
    kanji[c] = known[c];
  return {
    meta: {
      description:
        "KANJIDIC2 records of every kanji the daily words are written with. Generated by scripts/build-kanji-reference.mjs from the level snapshots in data/reference/; do not edit by hand.",
      source: { ...JAMDICT_SOURCE, licence: "KANJIDIC2 © EDRDG, CC BY-SA 4.0" },
      count: Object.keys(kanji).length,
    },
    kanji,
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const reference = buildKanjiReference();
  const next = `${JSON.stringify(reference, null, 1)}\n`;
  if (process.argv.includes("--check")) {
    const prev = readFileSync(join(ROOT, OUT_FILE), "utf8");
    if (prev !== next) {
      console.error(`${OUT_FILE} is out of date: run pnpm data:kanji`);
      process.exit(1);
    }
    console.log(`Checked ${OUT_FILE}`);
  } else {
    writeFileSync(join(ROOT, OUT_FILE), next);
    console.log(`Wrote ${OUT_FILE}: ${reference.meta.count} kanji`);
  }
}
