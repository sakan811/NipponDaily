/**
 * Builds data/reference/sentences/ (`pnpm data:sentences`): the example
 * sentences of every daily word, picked from one pinned Tatoeba export
 * (scripts/lib/tatoeba-export.mjs) by the rules in
 * scripts/lib/example-sentences.mjs.
 *
 * Offline and deterministic: the export's checksums are verified first, and the
 * same export gives the same snapshot. The pool word (reading, spelling and
 * whether JMdict reads the spelling several ways) comes from the word plans and
 * the committed level snapshots. Words with no qualifying sentence simply get
 * none. Each picked sentence then gets furigana (scripts/lib/furigana.mjs):
 * kuromoji's readings, kept only where Tatoeba's index or JMdict confirms them,
 * so this step does read the pinned JMdict (node_modules/.cache/, fetched and
 * checksum-verified on first use).
 *
 *   node scripts/build-sentences-reference.mjs [--dir <path>] [--check]
 *
 * `--dir` (or TATOEBA_DIR) names the directory with the extracted export; by
 * default `tatoeba/` in the repo root. `--check` fails if the committed
 * snapshot would change. Tatoeba's sentences are CC BY 2.0 FR
 * (https://creativecommons.org/licenses/by/2.0/fr/); each keeps its Tatoeba id
 * so the attribution stays traceable.
 */
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import kuromoji from "kuromoji";
import { toHiragana } from "wanakana";
import {
  TATOEBA_EXPORT,
  readExport,
  verifyExport,
} from "./lib/tatoeba-export.mjs";
import { pickExamples } from "./lib/example-sentences.mjs";
import { furiganaFor } from "./lib/furigana.mjs";
import {
  JAMDICT_SOURCE,
  ensureJamdictDb,
  openDictionary,
} from "./lib/jamdict.mjs";
import {
  loadSentenceSnapshot,
  writeSentenceSnapshot,
} from "./lib/sentence-snapshot.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
/** Shared with the reference builders, so jamdict-data is fetched once. */
const JAMDICT_CACHE = join(ROOT, "node_modules/.cache/n5-reference");
const KUROMOJI_VERSION = createRequire(import.meta.url)(
  "kuromoji/package.json",
).version;
const args = process.argv.slice(2);
const flagValue = (name) => {
  const i = args.indexOf(name);
  return i === -1 ? undefined : args[i + 1];
};

/** The meta every snapshot carries. */
export function snapshotMeta() {
  return {
    source: `Tatoeba (https://tatoeba.org), sentences with an English translation, read from the export of ${TATOEBA_EXPORT.date}`,
    license: "CC BY 2.0 FR — https://creativecommons.org/licenses/by/2.0/fr/",
    export: TATOEBA_EXPORT.date,
    files: Object.fromEntries(
      Object.entries(TATOEBA_EXPORT.files).map(([name, f]) => [name, f.sha256]),
    ),
    furigana: `Readings read by kuromoji ${KUROMOJI_VERSION} (IPADIC) and kept only where Tatoeba's index, or JMdict (${JAMDICT_SOURCE.package} ${JAMDICT_SOURCE.version}) giving the spelling one reading, confirms them`,
    note: "Generated by `pnpm data:sentences`: never edit by hand. Each sentence's `id` is its Tatoeba number (tatoeba.org/sentences/show/<id>), `enId` its translation's; `furigana` is its parts, `[text]` or `[kanji, reading]`, which join to `ja`.",
  };
}

/** The pool word of every day in the word plans, from the committed level
 *  snapshots: the plans, not the entries, so a new month can be built before
 *  `pnpm data:words` has made its entries. */
function poolWords(root) {
  const vocab = [];
  for (const level of ["n5", "n4", "n3", "n2", "n1"])
    vocab.push(
      ...JSON.parse(
        readFileSync(
          join(root, `data/reference/${level}-reference.json`),
          "utf8",
        ),
      ).vocab,
    );
  const words = [];
  const dir = join(root, "data/word-plan");
  for (const f of readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort())
    for (const plan of JSON.parse(readFileSync(join(dir, f), "utf8"))) {
      const found = vocab.filter(
        (v) => v.term === plan.term && (!plan.kana || v.kana === plan.kana),
      );
      if (found.length !== 1)
        throw new Error(
          `${plan.term}: ${found.length} pool words with that spelling${plan.kana ? ` and reading ${plan.kana}` : "; name the reading as `kana` in the plan"}`,
        );
      words.push({
        term: plan.term,
        kana: found[0].kana,
        spellingReadings: found[0].spellingReadings,
      });
    }
  return words;
}

/** The snapshot entries for every word, from an already-read export. */
export function buildSentences(words, corpus) {
  const entries = {};
  for (const word of words) {
    const examples = pickExamples(word, corpus);
    if (examples.length) entries[word.term] = examples;
  }
  return entries;
}

/** What reading a sentence needs: kuromoji, and JMdict's readings of a spelling. */
export async function openFuriganaTools() {
  const tokenizer = await new Promise((res, rej) =>
    kuromoji
      .builder({ dicPath: join(ROOT, "node_modules/kuromoji/dict") })
      .build((err, t) => (err ? rej(err) : res(t))),
  );
  const dict = openDictionary(await ensureJamdictDb(JAMDICT_CACHE));
  const memo = new Map();
  const jmdictReadings = (spelling) => {
    if (!memo.has(spelling)) memo.set(spelling, dict.readingsOf(spelling));
    return memo.get(spelling);
  };
  return { tokenizer, jmdictReadings };
}

/** Adds `furigana` to every example whose sentence got a verified reading.
 *  The index's own readings of each sentence come from the export. */
export function addFurigana(entries, corpus, { tokenizer, jmdictReadings }) {
  const wanted = new Set(
    Object.values(entries)
      .flat()
      .map((e) => String(e.id)),
  );
  const indexed = new Map();
  for (const [headword, hits] of corpus.index)
    for (const hit of hits) {
      if (!hit.reading || !wanted.has(hit.id)) continue;
      if (!indexed.has(hit.id)) indexed.set(hit.id, new Map());
      indexed.get(hit.id).set(headword, toHiragana(hit.reading));
    }
  for (const examples of Object.values(entries))
    for (const ex of examples) {
      const furigana = furiganaFor(ex.ja, ex.form, tokenizer.tokenize(ex.ja), {
        indexReadings: indexed.get(String(ex.id)) ?? new Map(),
        jmdictReadings,
      });
      if (furigana) ex.furigana = furigana;
    }
  return entries;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dir = resolve(
    flagValue("--dir") ??
      process.env.TATOEBA_DIR ??
      join(ROOT, TATOEBA_EXPORT.dir),
  );
  if (!existsSync(dir))
    throw new Error(
      `No Tatoeba export at ${dir}. Download the files named in scripts/lib/tatoeba-export.mjs, extract them there (or pass --dir <path>).`,
    );
  console.log(`Verifying ${dir}…`);
  await verifyExport(dir);
  console.log("Reading the export…");
  const corpus = readExport(dir);
  const entries = addFurigana(
    buildSentences(poolWords(ROOT), corpus),
    corpus,
    await openFuriganaTools(),
  );

  if (args.includes("--check")) {
    const now = loadSentenceSnapshot(ROOT);
    // Compared by term, whatever order the shards were read in.
    const canon = (o) => JSON.stringify(Object.entries(o).sort());
    const same =
      canon(now.entries) === canon(entries) &&
      JSON.stringify(now.meta) === JSON.stringify(snapshotMeta());
    if (!same) {
      console.error(
        "data/reference/sentences/ is out of date: run pnpm data:sentences",
      );
      process.exit(1);
    }
    console.log("Checked data/reference/sentences/");
  } else {
    const shards = writeSentenceSnapshot(ROOT, snapshotMeta(), entries);
    console.log(
      `Wrote sentences for ${Object.keys(entries).length} words into ${shards} file(s) under data/reference/sentences/`,
    );
  }
}
