    <h2 id="ai">Where AI may help, and where it may not</h2>
    <p>
      A model's output can be wrong in ways that read as confident, so AI is
      only given tasks whose output is allowed to be inaccurate: nothing it
      produces is shown to a reader as a fact unless a source backs it.
    </p>
    <ul>
      <li>
        <strong>OK:</strong> choosing which words go in a month (a poor pick
        costs nothing; the generator refuses a word with no usable source),
        drafting a headline (a hook, not a claim; a test limits its Japanese to
        what the evidence or pool contains), and writing code or tests, which CI
        then checks.
      </li>
      <li>
        <strong>Not OK:</strong> supplying a reading, meaning, level, layer,
        morpheme split, etymology or any other claim about a word.
      </li>
    </ul>
    <p>
      Before handing a task to a model, ask:
      <em
        >if this came back wrong, would a check catch it or would it simply not
        matter?</em
      >
      If neither, it must come from a source. The same goes for any new
      feature's data.
    </p>

    <h2>What the checks prove</h2>
    <DocDiagram
      label="The content tests read the committed evidence and every entry; a wrong claim fails CI"
      :nodes="checks.nodes"
      :edges="checks.edges"
    />
    <p>
      The content tests (<code>test/content/</code>, their own Vitest project,
      run by <code>pnpm test</code> in CI) regenerate every month and check each
      entry independently of the generator, so a generator bug can't vouch for
      itself.
    </p>
    <ul>
      <li>
        <strong>Generation</strong> (<code>word-generation.test.ts</code>): a
        committed entry equals, field for field, what the generator derives, so
        a derived field can't be edited by hand or left stale.
      </li>
      <li>
        <strong>Catalogue</strong>: every date and term is unique, no day
        between the first entry and the last is missing (the first and last
        months may be partial), and entries are sorted.
      </li>
      <li>
        <strong>Every entry</strong> (<code>words.test.ts</code>):
        <ul>
          <li>
            the term, reading, level and meaning equal the word list's, and its
            layer and processes are ones the site knows;
          </li>
          <li>
            <code>pos</code> holds only tags JMdict gives that word, and
            <code>register</code>, <code>field</code> and <code>dialect</code>
            only tags every matched sense carries;
          </li>
          <li>
            every <code>sources[].quote</code> is found
            <strong>verbatim</strong> (modulo whitespace and direction marks) in
            a Wiktionary Etymology section declared for the entry's
            <em>own reading</em>, from the dump the entry names (a page like
            大人 has one section per reading);
          </li>
          <li>
            the morphemes literally spell the word and join to
            <code>kana</code>; each non-<code>irregular</code> single-kanji
            morpheme has a reading KANJIDIC2 lists and a gloss KANJIDIC2 or the
            cited text backs;
          </li>
          <li>
            the headline mentions only Japanese the entry's evidence or the pool
            contains;
          </li>
          <li>
            an <code>unclear</code> entry quotes a hedged line, no snapshot pin
            is orphaned, each pin sits in the shard of the month that plans its
            word, and the snapshot records its source and licence.
          </li>
        </ul>
      </li>
      <li>
        <strong>JMdict, independently</strong>
        (<code>jmdict-crosscheck.test.ts</code>): an entry's priority codes are
        ones JMdict gives its spelling or reading; its register, field and
        dialect are exactly the tags every matched sense carries (and the
        register tags still occur in the pinned JMdict, so a renamed tag cannot
        silently stop matching); a word written with kanji that JMdict marks as
        a coinage made in Japan or an ateji, gikun or jukujikun spelling or
        reading carries that process; a European loan source means the borrowing
        process and the loanword layer (unless the cited text itself puts
        Chinese forward and hedges, as for 缶). It only confirms: the JMdict
        file pinned here gives no loan source for many loanwords (カメラ,
        ノート), so silence from JMdict proves nothing.
      </li>
      <li>
        <strong>Example sentences</strong> (<code>examples.test.ts</code>): each
        sentence is the committed snapshot's, holds the form it says the word
        takes, is a form of that word (its own spelling, an inflection that
        keeps the first character, or kana), has a translation and a readable
        length, and the snapshot names the export it came from. The sentences
        are not reviewed one by one: the export is the community's, and a short
        filter keeps out the plainly unsuitable; of a word's qualifying
        sentences, those with every kanji read come first. Each sentence's
        furigana joins back to its text, puts a reading only over kanji, in
        hiragana, and never across the edge of the word's form; almost every
        kanji of the sentences shown has one; the snapshot says how readings
        were checked.
      </li>
      <li>
        <strong>Pitch accent</strong> (<code>pitch.test.ts</code>): the snapshot
        names its source, licence and the file it was read from, holds only
        words in the catalogue with their own reading, gives each accent as a
        whole number no larger than the word's count of morae, and every entry
        shows the snapshot's accents and no others. The second source is named
        too, and every word that lost an accent is listed with what each source
        said, adding up to what was kept.
      </li>
      <li>
        <strong>Kanji</strong> (<code>kanji.test.ts</code>):
        <code>data/reference/kanji.json</code> holds exactly the kanji the
        entries are written with, each as the level snapshots have it.
      </li>
      <li>
        <strong>Stroke order</strong> (<code>strokes.test.ts</code>): the
        snapshot names its source, licence and release, holds only kanji of
        <code>kanji.json</code>, each with as many strokes as KANJIDIC2 counts,
        and covers nearly every kanji the entries use.
      </li>
      <li>
        <strong>Every word-list word, at every level</strong>
        (<code>vocabulary.test.ts</code> in <code>test/content/</code> and
        <code>test/content/{n4,n3,n2,n1}/</code>): it is in JMdict with that
        reading, has no meaning that reverses JMdict's, has its reading attested
        (<code>reading-attested.test.ts</code>), and every enrichment in
        <code>shared/meanings.ts</code> is backed by JMdict. A staleness check
        fails if a reference file no longer matches what
        <code>servedVocab()</code> would produce.
      </li>
    </ul>

    <aside class="note">
      <span class="note-title">What these checks cannot prove</span>
      <p>
        That Wiktionary is <em>right</em> (only that the dump says so), that
        JMdict's tags suit every usage, or that a headline is a fair hook. Where
        Wiktionary hedges, the entry quotes the hedge and flags it instead of
        choosing a winner.
      </p>
      <p>
        The dump is machine-extracted, and two of its faults are known. It drops
        Wiktionary's “etymology incomplete” banners, so a word the page marks
        incomplete may not be flagged unclear. And it can attach one reading's
        etymology to another (道 みち received the Middle Chinese section of
        どう). The generator refuses a native reading whose section opens “From
        Middle Chinese”, but a swap between two readings of the same kind would
        not be caught, so read each new entry once.
      </p>
    </aside>

